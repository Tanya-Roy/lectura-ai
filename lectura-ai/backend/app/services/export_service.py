class NumberedCanvas(canvas.Canvas):
    """Two-pass ReportLab canvas to compute dynamic total page numbers."""

    def __init__(self, *args, **kwargs):
        super().__init__(*args, **kwargs)
        self._saved_page_states = []

    def showPage(self):
        self._saved_page_states.append(dict(self.__dict__))
        self._startPage()

    def save(self):
        num_pages = len(self._saved_page_states)
        for state in self._saved_page_states:
            self.__dict__.update(state)
            self.draw_page_decorations(num_pages)
            super().showPage()
        super().save()

    def draw_page_decorations(self, total_pages: int):
        self.saveState()
        self.setFont("Helvetica", 8)
        self.setFillColor(HexColor("#64748b"))

        # Skip running header/footer on title cover page
        if self._pageNumber > 1:
            # Header
            self.drawString(54, 800, "Lectura AI  |  Verified Academic Study Notes")
            self.setStrokeColor(HexColor("#e2e8f0"))
            self.setLineWidth(0.5)
            self.line(54, 792, 540, 792)

            # Footer
            self.line(54, 50, 540, 50)
            page_text = f"Page {self._pageNumber} of {total_pages}"
            self.drawRightString(540, 38, page_text)
            self.drawString(54, 38, "Generated by Lectura AI  •  https://lectura.ai")

        self.restoreState()


class ExportService:
    """Provides PDF and DOCX document generation from Markdown text."""

    @staticmethod
    def _clean_latex_to_text(math_str: str) -> str:
        """Converts common LaTeX operators and symbols into readable Unicode for exports."""
        s = math_str.strip()
        replacements = [
            (r"\\mathbb\{R\}", "ℝ"),
            (r"\\mathbb\{N\}", "ℕ"),
            (r"\\mathbb\{Z\}", "ℤ"),
            (r"\\mathbb\{E\}", "𝔼"),
            (r"\\mathcal\{L\}", "ℒ"),
            (r"\\mathcal\{R\}", "ℛ"),
            (r"\\mathcal\{D\}", "𝒟"),
            (r"\\mathcal\{O\}", "𝒪"),
            (r"\\theta", "θ"),
            (r"\\lambda", "λ"),
            (r"\\sigma", "σ"),
            (r"\\epsilon", "ε"),
            (r"\\eta", "η"),
            (r"\\mu", "μ"),
            (r"\\nabla", "∇"),
            (r"\\sum_\{[^}]*\}\^\{[^}]*\}", "∑"),
            (r"\\sum", "∑"),
            (r"\\min", "min"),
            (r"\\max", "max"),
            (r"\\to", "→"),
            (r"\\infty", "∞"),
            (r"\\in", "∈"),
            (r"\\le", "≤"),
            (r"\\ge", "≥"),
            (r"\\neq", "≠"),
            (r"\\approx", "≈"),
            (r"\\times", "×"),
            (r"\\cdot", "·"),
            (r"\\|", "‖"),
            (r"\\frac\{([^}]+)\}\{([^}]+)\}", r"(\1 / \2)"),
            (r"\\sqrt\{([^}]+)\}", r"√(\1)"),
            (r"\\hat\{([^}]+)\}", r"\1̂"),
            (r"\\left", ""),
            (r"\\right", ""),
            (r"\\,", " "),
            (r"\\;", " "),
            (r"\\!", ""),
            (r"\{", ""),
            (r"\}", ""),
            (r"\\\\", ""),
        ]
        for pattern, repl in replacements:
            s = re.sub(pattern, repl, s)
        return s.strip()

    @classmethod
    def markdown_to_pdf(cls, markdown_content: str, title: str = "Lectura AI Study Notes") -> bytes:
        """Converts Markdown lecture notes into a styled PDF document using ReportLab."""
        buffer = io.BytesIO()

        # Document Setup
        doc = SimpleDocTemplate(
            buffer,
            pagesize=A4,
            leftMargin=54,
            rightMargin=54,
            topMargin=54,
            bottomMargin=54,
        )

        styles = getSampleStyleSheet()

        # Custom typography styles
        title_style = ParagraphStyle(
            "DocTitle",
            parent=styles["Normal"],
            fontName="Helvetica-Bold",
            fontSize=24,
            leading=28,
            textColor=HexColor("#0f172a"),
            alignment=TA_LEFT,
            spaceAfter=10,
        )

        h1_style = ParagraphStyle(
            "Heading1_Custom",
            parent=styles["Heading1"],
            fontName="Helvetica-Bold",
            fontSize=16,
            leading=20,
            textColor=HexColor("#1e293b"),
            spaceBefore=14,
            spaceAfter=8,
            keepWithNext=True,
        )

        h2_style = ParagraphStyle(
            "Heading2_Custom",
            parent=styles["Heading2"],
            fontName="Helvetica-Bold",
            fontSize=13,
            leading=17,
            textColor=HexColor("#334155"),
            spaceBefore=12,
            spaceAfter=6,
            keepWithNext=True,
        )

        h3_style = ParagraphStyle(
            "Heading3_Custom",
            parent=styles["Heading3"],
            fontName="Helvetica-Bold",
            fontSize=11,
            leading=15,
            textColor=HexColor("#475569"),
            spaceBefore=8,
            spaceAfter=4,
            keepWithNext=True,
        )

        body_style = ParagraphStyle(
            "Body_Custom",
            parent=styles["BodyText"],
            fontName="Helvetica",
            fontSize=9.5,
            leading=14,
            textColor=HexColor("#1e293b"),
            spaceAfter=6,
        )

        bullet_style = ParagraphStyle(
            "Bullet_Custom",
            parent=body_style,
            leftIndent=16,
            firstLineIndent=-10,
            spaceAfter=4,
        )

        quote_style = ParagraphStyle(
            "Quote_Custom",
            parent=body_style,
            fontName="Helvetica-Oblique",
            fontSize=9,
            leading=13.5,
            textColor=HexColor("#1e3a8a"),
            leftIndent=18,
            rightIndent=18,
            spaceBefore=6,
            spaceAfter=6,
        )

        math_style = ParagraphStyle(
            "Math_Custom",
            parent=body_style,
            fontName="Courier-Bold",
            fontSize=9.5,
            leading=13,
            textColor=HexColor("#0f172a"),
            alignment=TA_CENTER,
            spaceBefore=6,
            spaceAfter=6,
        )

        meta_style = ParagraphStyle(
            "Meta_Custom",
            parent=body_style,
            fontSize=8.5,
            leading=12,
            textColor=HexColor("#64748b"),
        )

        story = []

        # --- Title Page Header ---
        story.append(Paragraph("LECTURA AI  •  STUDY NOTES WORKSPACE", meta_style))
        story.append(Spacer(1, 6))
        story.append(Paragraph(title, title_style))
        story.append(
            Paragraph(
                f"Generated on {datetime.now(timezone.utc).strftime('%B %d, %Y')}  •  Academic Synthesis Engine",
                meta_style,
            )
        )
        story.append(Spacer(1, 10))
        story.append(HRFlowable(width="100%", thickness=1.5, color=HexColor("#4f46e5"), spaceAfter=14))

        # --- Parse Markdown Body ---
        lines = markdown_content.split("\n")
        in_code_block = False
        code_buffer = []

        for line in lines:
            line_str = line.strip()

            # Code block detection
            if line_str.startswith("```"):
                if in_code_block:
                    in_code_block = False
                    code_text = "<br/>".join(code_buffer)
                    code_p = Paragraph(f"<font face='Courier' size=8 color='#0f172a'>{code_text}</font>", math_style)
                    story.append(code_p)
                    code_buffer = []
                else:
                    in_code_block = True
                    code_buffer = []
                continue

            if in_code_block:
                escaped_code = line.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;").replace(" ", "&nbsp;")
                code_buffer.append(escaped_code)
                continue

            if not line_str:
                story.append(Spacer(1, 4))
                continue

            # Display Math: $$ ... $$
            if line_str.startswith("$$") and line_str.endswith("$$") and len(line_str) > 4:
                math_raw = line_str[2:-2]
                math_clean = cls._clean_latex_to_text(math_raw)
                story.append(Paragraph(f"[ {math_clean} ]", math_style))
                continue

            # Horizontal Rule
            if line_str in ["---", "***", "___"]:
                story.append(HRFlowable(width="100%", thickness=0.5, color=HexColor("#cbd5e1"), spaceBefore=6, spaceAfter=8))
                continue

            # Headings
            if line_str.startswith("# "):
                h_text = line_str[2:].strip()
                story.append(Paragraph(h_text, h1_style))
                continue
            elif line_str.startswith("## "):
                h_text = line_str[3:].strip()
                story.append(Paragraph(h_text, h2_style))
                continue
            elif line_str.startswith("### "):
                h_text = line_str[4:].strip()
                story.append(Paragraph(h_text, h3_style))
                continue

            # Blockquotes / Definitions / Supplementary Callouts
            if line_str.startswith(">"):
                quote_text = line_str.lstrip("> ").strip()
                clean_q = quote_text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
                clean_q = re.sub(r"\*\*([^*]+)\*\*", r"<b>\1</b>", clean_q)
                clean_q = re.sub(r"\*([^*]+)\*", r"<i>\1</i>", clean_q)
                story.append(Paragraph(clean_q, quote_style))
                continue

            # Bullets
            if line_str.startswith("- ") or line_str.startswith("* ") or line_str.startswith("- [x] ") or line_str.startswith("- [ ] "):
                b_text = re.sub(r"^[-*]\s*(\[[ x]\]\s*)?", "", line_str).strip()
                clean_b = b_text.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
                # Clean inline math
                clean_b = re.sub(r"\$([^$]+)\$", lambda m: f"<i>{cls._clean_latex_to_text(m.group(1))}</i>", clean_b)
                clean_b = re.sub(r"\*\*([^*]+)\*\*", r"<b>\1</b>", clean_b)
                clean_b = re.sub(r"\*([^*]+)\*", r"<i>\1</i>", clean_b)
                clean_b = re.sub(r"`([^`]+)`", r"<font face='Courier'>\1</font>", clean_b)
                story.append(Paragraph(f"• &nbsp; {clean_b}", bullet_style))
                continue

            # Standard Paragraph
            clean_p = line_str.replace("&", "&amp;").replace("<", "&lt;").replace(">", "&gt;")
            clean_p = re.sub(r"\$([^$]+)\$", lambda m: f"<i>{cls._clean_latex_to_text(m.group(1))}</i>", clean_p)
            clean_p = re.sub(r"\*\*([^*]+)\*\*", r"<b>\1</b>", clean_p)
            clean_p = re.sub(r"\*([^*]+)\*", r"<i>\1</i>", clean_p)
            clean_p = re.sub(r"`([^`]+)`", r"<font face='Courier'>\1</font>", clean_p)

            story.append(Paragraph(clean_p, body_style))

        # Build PDF with two-pass canvas
        doc.build(story, canvasmaker=NumberedCanvas)
        return buffer.getvalue()

    @classmethod
    def markdown_to_docx(cls, markdown_content: str, title: str = "Lectura AI Study Notes") -> bytes:
        """Converts Markdown lecture notes into a formatted Microsoft Word document (.docx)."""
        doc = Document()

        # Page Setup: 1-inch margins
        for section in doc.sections:
            section.top_margin = Inches(1.0)
            section.bottom_margin = Inches(1.0)
            section.left_margin = Inches(1.0)
            section.right_margin = Inches(1.0)

            # Footer
            footer = section.footer
            footer_para = footer.paragraphs[0]
            footer_para.alignment = WD_ALIGN_PARAGRAPH.RIGHT
            f_run = footer_para.add_run("Lectura AI  •  Verified Academic Notes")
            f_run.font.name = "Calibri"
            f_run.font.size = Pt(8.5)
            f_run.font.color.rgb = RGBColor(148, 163, 184)

        # Document Header
        title_para = doc.add_paragraph()
        title_run = title_para.add_run(title)
        title_run.font.name = "Calibri"
        title_run.font.size = Pt(22)
        title_run.font.bold = True
        title_run.font.color.rgb = RGBColor(15, 23, 42)
        title_para.paragraph_format.space_after = Pt(2)

        sub_para = doc.add_paragraph()
        sub_run = sub_para.add_run(f"Generated by Lectura AI on {datetime.now(timezone.utc).strftime('%B %d, %Y')}")
        sub_run.font.name = "Calibri"
        sub_run.font.size = Pt(9)
        sub_run.font.color.rgb = RGBColor(100, 116, 139)
        sub_para.paragraph_format.space_after = Pt(16)

        # Parse Lines
        lines = markdown_content.split("\n")
        in_code = False
        code_lines = []

        for line in lines:
            line_str = line.strip()

            # Code Blocks
            if line_str.startswith("```"):
                if in_code:
                    in_code = False
                    p_code = doc.add_paragraph()
                    p_code.paragraph_format.left_indent = Inches(0.4)
                    r_code = p_code.add_run("\n".join(code_lines))
                    r_code.font.name = "Consolas"
                    r_code.font.size = Pt(9)
                    r_code.font.color.rgb = RGBColor(15, 23, 42)
                    code_lines = []
                else:
                    in_code = True
                    code_lines = []
                continue

            if in_code:
                code_lines.append(line)
                continue

            if not line_str:
                continue

            # Display Math: $$ ... $$
            if line_str.startswith("$$") and line_str.endswith("$$") and len(line_str) > 4:
                math_raw = line_str[2:-2]
                math_clean = cls._clean_latex_to_text(math_raw)
                p_math = doc.add_paragraph()
                p_math.alignment = WD_ALIGN_PARAGRAPH.CENTER
                p_math.paragraph_format.space_before = Pt(6)
                p_math.paragraph_format.space_after = Pt(6)
                r_math = p_math.add_run(f"[  {math_clean}  ]")
                r_math.font.name = "Cambria Math"
                r_math.font.size = Pt(10)
                r_math.font.bold = True
                r_math.font.color.rgb = RGBColor(30, 41, 59)
                continue

            # Horizontal Rule
            if line_str in ["---", "***", "___"]:
                p_hr = doc.add_paragraph()
                p_hr.paragraph_format.space_before = Pt(6)
                p_hr.paragraph_format.space_after = Pt(8)
                r_hr = p_hr.add_run("—" * 48)
                r_hr.font.color.rgb = RGBColor(203, 213, 225)
                continue

            # Headings
            if line_str.startswith("# "):
                h = doc.add_heading(level=1)
                r = h.add_run(line_str[2:].strip())
                r.font.name = "Calibri"
                r.font.color.rgb = RGBColor(15, 23, 42)
                continue
            elif line_str.startswith("## "):
                h = doc.add_heading(level=2)
                r = h.add_run(line_str[3:].strip())
                r.font.name = "Calibri"
                r.font.color.rgb = RGBColor(30, 41, 59)
                continue
            elif line_str.startswith("### "):
                h = doc.add_heading(level=3)
                r = h.add_run(line_str[4:].strip())
                r.font.name = "Calibri"
                r.font.color.rgb = RGBColor(71, 85, 105)
                continue

            # Blockquotes / Definitions
            if line_str.startswith(">"):
                quote_text = line_str.lstrip("> ").strip()
                p_q = doc.add_paragraph()
                p_q.paragraph_format.left_indent = Inches(0.3)
                p_q.paragraph_format.space_before = Pt(4)
                p_q.paragraph_format.space_after = Pt(4)
                cls._append_formatted_runs(p_q, quote_text, italic_override=True)
                continue

            # Bullets
            if line_str.startswith("- ") or line_str.startswith("* ") or line_str.startswith("- [x] ") or line_str.startswith("- [ ] "):
                b_text = re.sub(r"^[-*]\s*(\[[ x]\]\s*)?", "", line_str).strip()
                p_b = doc.add_paragraph(style="List Bullet")
                p_b.paragraph_format.space_after = Pt(3)
                cls._append_formatted_runs(p_b, b_text)
                continue

            # Standard paragraph
            p = doc.add_paragraph()
            p.paragraph_format.space_after = Pt(6)
            p.paragraph_format.line_spacing = 1.15
            cls._append_formatted_runs(p, line_str)

        # Save to bytes buffer
        buffer = io.BytesIO()
        doc.save(buffer)
        return buffer.getvalue()

    @classmethod
    def _append_formatted_runs(cls, paragraph, text: str, italic_override: bool = False):
        """Helper to break paragraph into bold, italic, code, and LaTeX text runs."""
        # Clean inline math first: $...$ -> clean unicode
        text_processed = re.sub(
            r"\$([^$]+)\$",
            lambda m: f"*{cls._clean_latex_to_text(m.group(1))}*",
            text,
        )

        # Tokenize by bold **...** and *...*
        tokens = re.split(r"(\*\*[^*]+\*\*|\*[^*]+\*|`[^`]+`)", text_processed)
        for token in tokens:
            if not token:
                continue
            if token.startswith("**") and token.endswith("**"):
                run = paragraph.add_run(token[2:-2])
                run.bold = True
                run.italic = italic_override
                run.font.name = "Calibri"
                run.font.size = Pt(10)
            elif token.startswith("*") and token.endswith("*"):
                run = paragraph.add_run(token[1:-1])
                run.italic = True
                run.font.name = "Calibri"
                run.font.size = Pt(10)
            elif token.startswith("`") and token.endswith("`"):
                run = paragraph.add_run(token[1:-1])
                run.font.name = "Consolas"
                run.font.size = Pt(9.5)
                run.font.color.rgb = RGBColor(15, 23, 42)
            else:
                run = paragraph.add_run(token)
                run.italic = italic_override
                run.font.name = "Calibri"
                run.font.size = Pt(10)
                run.font.color.rgb = RGBColor(30, 41, 59)
